-- BTS "Reporting Carrier On-Time Performance (1987-present)", one row per flight.
-- https://www.transtats.bts.gov/Fields.asp?gnoyr_VQ=FGJ
-- Column names match the BTS CSV header so files load by name. Times (CRSDepTime
-- etc.) are local to the airport, as HHMM numbers (729 = 07:29; 2400 = midnight).
-- One partition per month: load-flights.sh replaces a whole month on reload.
CREATE TABLE IF NOT EXISTS faa.ontime
(
    Year                            UInt16,
    Quarter                         UInt8,
    Month                           UInt8,
    DayofMonth                      UInt8,
    DayOfWeek                       UInt8,
    FlightDate                      Date,
    Reporting_Airline               LowCardinality(String),
    DOT_ID_Reporting_Airline        UInt32,
    IATA_CODE_Reporting_Airline     LowCardinality(String),
    Tail_Number                     String,
    Flight_Number_Reporting_Airline UInt32,
    OriginAirportID                 UInt32,
    OriginAirportSeqID              UInt32,
    OriginCityMarketID              UInt32,
    Origin                          LowCardinality(String),
    OriginCityName                  LowCardinality(String),
    OriginState                     LowCardinality(String),
    OriginStateFips                 LowCardinality(String),
    OriginStateName                 LowCardinality(String),
    OriginWac                       UInt16,
    DestAirportID                   UInt32,
    DestAirportSeqID                UInt32,
    DestCityMarketID                UInt32,
    Dest                            LowCardinality(String),
    DestCityName                    LowCardinality(String),
    DestState                       LowCardinality(String),
    DestStateFips                   LowCardinality(String),
    DestStateName                   LowCardinality(String),
    DestWac                         UInt16,
    CRSDepTime                      UInt16,
    DepTime                         Nullable(UInt16),
    DepDelay                        Nullable(Float32),
    DepDelayMinutes                 Nullable(Float32),
    DepDel15                        Nullable(Float32),
    DepartureDelayGroups            Nullable(Int8),
    DepTimeBlk                      LowCardinality(String),
    TaxiOut                         Nullable(Float32),
    WheelsOff                       Nullable(UInt16),
    WheelsOn                        Nullable(UInt16),
    TaxiIn                          Nullable(Float32),
    CRSArrTime                      UInt16,
    ArrTime                         Nullable(UInt16),
    ArrDelay                        Nullable(Float32),
    ArrDelayMinutes                 Nullable(Float32),
    ArrDel15                        Nullable(Float32),
    ArrivalDelayGroups              Nullable(Int8),
    ArrTimeBlk                      LowCardinality(String),
    Cancelled                       Float32,
    CancellationCode                LowCardinality(String),
    Diverted                        Float32,
    CRSElapsedTime                  Nullable(Float32),
    ActualElapsedTime               Nullable(Float32),
    AirTime                         Nullable(Float32),
    Flights                         Float32,
    Distance                        Float32,
    DistanceGroup                   UInt8,
    CarrierDelay                    Nullable(Float32),
    WeatherDelay                    Nullable(Float32),
    NASDelay                        Nullable(Float32),
    SecurityDelay                   Nullable(Float32),
    LateAircraftDelay               Nullable(Float32),
    FirstDepTime                    Nullable(UInt16),
    TotalAddGTime                   Nullable(Float32),
    LongestAddGTime                 Nullable(Float32),
    DivAirportLandings              Nullable(UInt8),
    DivReachedDest                  Nullable(Float32),
    DivActualElapsedTime            Nullable(Float32),
    DivArrDelay                     Nullable(Float32),
    DivDistance                     Nullable(Float32),
    Div1Airport                     LowCardinality(String),
    Div1AirportID                   Nullable(UInt32),
    Div1AirportSeqID                Nullable(UInt32),
    Div1WheelsOn                    Nullable(UInt16),
    Div1TotalGTime                  Nullable(Float32),
    Div1LongestGTime                Nullable(Float32),
    Div1WheelsOff                   Nullable(UInt16),
    Div1TailNum                     String,
    Div2Airport                     LowCardinality(String),
    Div2AirportID                   Nullable(UInt32),
    Div2AirportSeqID                Nullable(UInt32),
    Div2WheelsOn                    Nullable(UInt16),
    Div2TotalGTime                  Nullable(Float32),
    Div2LongestGTime                Nullable(Float32),
    Div2WheelsOff                   Nullable(UInt16),
    Div2TailNum                     String,
    Div3Airport                     LowCardinality(String),
    Div3AirportID                   Nullable(UInt32),
    Div3AirportSeqID                Nullable(UInt32),
    Div3WheelsOn                    Nullable(UInt16),
    Div3TotalGTime                  Nullable(Float32),
    Div3LongestGTime                Nullable(Float32),
    Div3WheelsOff                   Nullable(UInt16),
    Div3TailNum                     String,
    Div4Airport                     LowCardinality(String),
    Div4AirportID                   Nullable(UInt32),
    Div4AirportSeqID                Nullable(UInt32),
    Div4WheelsOn                    Nullable(UInt16),
    Div4TotalGTime                  Nullable(Float32),
    Div4LongestGTime                Nullable(Float32),
    Div4WheelsOff                   Nullable(UInt16),
    Div4TailNum                     String,
    Div5Airport                     LowCardinality(String),
    Div5AirportID                   Nullable(UInt32),
    Div5AirportSeqID                Nullable(UInt32),
    Div5WheelsOn                    Nullable(UInt16),
    Div5TotalGTime                  Nullable(Float32),
    Div5LongestGTime                Nullable(Float32),
    Div5WheelsOff                   Nullable(UInt16),
    Div5TailNum                     String
)
ENGINE = MergeTree
PARTITION BY toYYYYMM(FlightDate)
ORDER BY (FlightDate, Origin, Reporting_Airline);
